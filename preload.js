const { contextBridge, ipcRenderer } = require('electron');

const call = (ch) => (...a) => ipcRenderer.invoke(ch, ...a);

contextBridge.exposeInMainWorld('api', {
  config: call('config:get'),
  googleConnect: call('google:connect'),
  msConnect: call('ms:connect'),
  accountReconnect: call('account:reconnect'),
  accountRemove: call('account:remove'),
  mail: call('mail:fetch'),
  jiraConnect: call('jira:connect'),
  jiraDisconnect: call('jira:disconnect'),
  jira: call('jira:fetch'),
  sfConnect: call('sf:connect'),
  sfDisconnect: call('sf:disconnect'),
  sf: call('sf:fetch'),
  asanaConnect: call('asana:connect'),
  asanaWorkspace: call('asana:workspace'),
  asanaDisconnect: call('asana:disconnect'),
  aiConnect: call('ai:connect'),
  aiPlatform: call('ai:platform'),
  aiClaudeCode: call('ai:claudecode'),
  aiDisconnect: call('ai:disconnect'),
  analyze: call('ai:analyze'),
  aiCached: call('ai:cached'),
  aiSave: call('ai:save'),
  everhourConnect: call('everhour:connect'),
  everhourDisconnect: call('everhour:disconnect'),
  everhour: call('everhour:fetch'),
  asana: call('asana:fetch'),
  links: call('links:get'),
  urgency: call('urgency:get'),
  filters: call('filters:get'),
  setFilters: call('filters:set'),
  setUrgency: call('urgency:set'),
  setLinks: call('links:set'),
  open: call('open:external'),
  pin: call('ui:pin'),
  widget: call('ui:widget'),
  openAtLogin: call('ui:openAtLogin'),
  showWindow: call('win:show'),
  attachments: call('asana:attachments'),
  upload: call('asana:upload'),
  handoff: call('handoff:task'),
  mcpEnable: call('mcp:enable'),
  mcpDisable: call('mcp:disable'),
  onLinks: (fn) => ipcRenderer.on('links:changed', (_e, links) => fn(links)),
  onTimerChanged: (fn) => ipcRenderer.on('timer:changed', () => fn()),
  onOpenTask: (fn) => ipcRenderer.on('open-task', (_e, gid) => fn(gid)),
  setTheme: call('ui:theme'),
  pickWallpaper: call('wallpaper:pick'),
  wallpaper: call('wallpaper:get'),
  quit: call('win:quit'),
  setCloseAction: call('ui:closeAction'),
  onCloseRequest: (fn) => ipcRenderer.on('close-request', () => fn()),
  onUi: (fn) => ipcRenderer.on('ui:changed', (_e, ui) => fn(ui)),
});
